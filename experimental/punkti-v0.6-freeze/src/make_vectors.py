#!/usr/bin/env python3
"""Generate deterministic artifacts only after both isolated implementations pass."""
import json
from vector_suite import HOME, Runner, definitions, equal, fixtures


def main():
    doc = definitions(fixtures())
    observations = {}
    for vector in doc['vectors']:
        outputs = []
        for kind in ('ref', 'nb'):
            runner = Runner(kind, doc)
            outputs.append(runner.run(vector))
            if hasattr(runner, 'non_normative'):
                observations[kind] = runner.non_normative
        equal(outputs[0], outputs[1], vector['id'] + ' normative parity')
        print(vector['id'] + ': ref PASS; nb PASS; normative equality PASS', flush=True)
    doc['non_normative_observations'] = observations
    lines = ['# Punkti 0.6 normative freeze-candidate vectors', '',
             'Generated by `src/make_vectors.py`; neither implementation is imported into this process.',
             'These vectors are a freeze candidate, not a release or freeze approval.', '',
             '## Encoding and execution', '',
             'All `*_utf8` strings below denote exact UTF-8 bytes after JSON string unescaping.',
             '`body_utf8` is the exact HTTP request body; `target` is the exact request target.',
             'HTTP uses loopback with dynamic ports; Host and transport header order are not normative.',
             'Adapter commands use JSON-lines; import_json receives base64 of the exact UTF-8 bytes.',
             'The seed is SHA-256 of the UTF-8 literal `' + doc['seed_literal'] + '`:',
             '`' + doc['seed_hex'] + '`. No timestamps, ports or random epochs enter this artifact.',
             'Server epochs are runtime values: compare tokens to that server’s HELLO epoch,',
             'and echo complete returned tokens. Canonical atom JSON member order is not normative.',
             'Error message text and implementation-specific error envelopes are not normative;',
             'HTTP statuses, classifications, admissions and state transitions asserted here are.',
             'V5 empty PUSH is labelled non_normative and excluded from the 13-vector normative total.',
             'A seeded fixture means adapter add(spec), with admitted=true and exact canonical fields checked.',
             'V7 import_json returns only ok/error by contract: accepted JSON is checked against the',
             'pinned atom and independently minted zero-timestamp C/R; the import return bytes are not exposed.', '',
             '## Canonical fixtures', '',
             'All canonical fields below are cross-checked against both independent mint/signing paths.',
             'C and S are hex; R and sig are canonical base64. sha256_R covers the exact R bytes.',
             'The zero fixture is the canonical zero-timestamp fixture for V7.', '',
             '```json', json.dumps(doc['fixtures'], indent=2, ensure_ascii=True), '```', '']
    for v in doc['vectors']:
        lines += ['## ' + v['id'] + ' — ' + v['title'], '',
                  v['input']['description'], '', v['expected']['description'], '',
                  '**State transition:** ' + v['state_transition']['description'], '',
                  'Exact inputs and machine-checkable expectations:', '',
                  '```json', json.dumps(v, indent=2, ensure_ascii=True), '```', '']
    lines += ['## Non-normative observations', '', 'Not included in normative pass/fail or equality totals.', '',
              '```json', json.dumps(observations, indent=2, sort_keys=True), '```', '']
    (HOME / 'vectors.json').write_text(json.dumps(doc, indent=2, ensure_ascii=True, sort_keys=True)+'\n')
    (HOME / 'docs/NORMATIVE_VECTORS.md').write_text('\n'.join(lines))
    print(f"{len(doc['vectors'])} normative vectors × 2 implementations PASS; {len(doc['vectors'])} equality comparisons PASS; 1 non-normative subcase excluded.")


if __name__ == '__main__':
    main()
